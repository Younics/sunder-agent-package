#!/usr/bin/env bash
set -euo pipefail
export LC_ALL=C

if [[ $# -ne 6 ]]; then
  printf 'Usage: generate-agent-publication-handoff.sh <release-assets-directory> <release-id> <tag> <source-sha> <release-provenance-run-attempt> <verified-release-assets-sha256>\n' >&2
  exit 2
fi

[[ -d "$1" && ! -L "$1" ]] \
  || { printf 'Publication handoff input must be a real release-assets directory.\n' >&2; exit 2; }
asset_directory="$(cd "$1" && pwd)"
release_id="$2"
tag="$3"
source_sha="$4"
provenance_run_attempt="$5"
verified_release_assets_sha256="$6"
handoff_name='publication-handoff-provenance.json'
handoff="$asset_directory/$handoff_name"
script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
release_source_directory="${SUNDER_AGENT_RELEASE_SOURCE_DIRECTORY:-$script_dir/../..}"

: "${GITHUB_REF:?GITHUB_REF is required}"
: "${GITHUB_REF_NAME:?GITHUB_REF_NAME is required}"
: "${GITHUB_REPOSITORY:?GITHUB_REPOSITORY is required}"
: "${GITHUB_RUN_ATTEMPT:?GITHUB_RUN_ATTEMPT is required}"
: "${GITHUB_RUN_ID:?GITHUB_RUN_ID is required}"
: "${GITHUB_SHA:?GITHUB_SHA is required}"
: "${GITHUB_WORKFLOW:?GITHUB_WORKFLOW is required}"
: "${GITHUB_WORKFLOW_REF:?GITHUB_WORKFLOW_REF is required}"

[[ "$release_id" =~ ^[1-9][0-9]*$ \
    && "$provenance_run_attempt" =~ ^[1-9][0-9]*$ \
    && "$GITHUB_RUN_ATTEMPT" =~ ^[1-9][0-9]*$ \
    && "$GITHUB_RUN_ID" =~ ^[1-9][0-9]*$ ]] \
  || { printf 'Publication release, run, and attempt coordinates must be positive decimal integers.\n' >&2; exit 2; }
[[ "$source_sha" =~ ^[0-9a-f]{40}$ && "$GITHUB_SHA" == "$source_sha" ]] \
  || { printf 'Publication handoff source must be the exact current lowercase Git SHA.\n' >&2; exit 2; }
[[ "$verified_release_assets_sha256" =~ ^[0-9a-f]{64}$ ]] \
  || { printf 'Publication handoff requires the publisher verified-assets SHA-256.\n' >&2; exit 2; }
[[ "$tag" =~ ^agent/v((0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)(-([0-9A-Za-z-]+)(\.[0-9A-Za-z-]+)*)?)$ \
    && "$GITHUB_REF" == "refs/tags/$tag" \
    && "$GITHUB_REF_NAME" == "$tag" ]] \
  || { printf 'Publication handoff tag and workflow ref do not agree.\n' >&2; exit 2; }
expected_workflow_ref="$GITHUB_REPOSITORY/.github/workflows/sunder-package-release.yml@refs/tags/$tag"
[[ "$GITHUB_WORKFLOW" == 'Sunder Agent Family Release' \
    && "$GITHUB_WORKFLOW_REF" == "$expected_workflow_ref" ]] \
  || { printf 'Publication handoff must be generated by the mandated tag-push workflow.\n' >&2; exit 2; }
decimal_lte() {
  local left="$1"
  local right="$2"
  ((${#left} < ${#right})) \
    || { ((${#left} == ${#right})) && [[ "$left" == "$right" || "$left" < "$right" ]]; }
}
decimal_lte "$provenance_run_attempt" "$GITHUB_RUN_ATTEMPT" \
  || { printf 'Immutable release provenance cannot originate from a future run attempt.\n' >&2; exit 2; }
[[ ! -e "$handoff" && ! -L "$handoff" ]] \
  || { printf 'Publication handoff already exists: %s\n' "$handoff" >&2; exit 1; }

for required_command in cut find gh jq mv python3 tr wc; do
  command -v "$required_command" >/dev/null 2>&1 \
    || { printf '%s is required to generate publication handoff provenance.\n' "$required_command" >&2; exit 127; }
done
if ! command -v sha256sum >/dev/null 2>&1 && ! command -v shasum >/dev/null 2>&1; then
  printf 'sha256sum or shasum is required to generate publication handoff provenance.\n' >&2
  exit 127
fi

hash_file() {
  if command -v sha256sum >/dev/null 2>&1; then sha256sum "$1" | cut -d ' ' -f 1
  else shasum -a 256 "$1" | cut -d ' ' -f 1; fi
}

hash_stream() {
  if command -v sha256sum >/dev/null 2>&1; then sha256sum | cut -d ' ' -f 1
  else shasum -a 256 | cut -d ' ' -f 1; fi
}

shopt -s nullglob
release_assets=("$asset_directory"/*)
unexpected_entry="$(find "$asset_directory" -mindepth 1 -maxdepth 1 ! -type f -print -quit)"
actual_count="$(find "$asset_directory" -mindepth 1 -maxdepth 1 -type f | wc -l | tr -d '[:space:]')"
[[ -z "$unexpected_entry" && "$actual_count" == 21 && "${#release_assets[@]}" == 21 ]] \
  || { printf 'Publication handoff requires exactly 21 immutable release assets.\n' >&2; exit 1; }
for asset in "${release_assets[@]}"; do
  [[ -f "$asset" && ! -L "$asset" ]] \
    || { printf 'Publication handoff input is not a regular immutable release asset: %s\n' "$asset" >&2; exit 1; }
done

release_provenance="$asset_directory/release-provenance.json"
[[ -f "$release_provenance" && ! -L "$release_provenance" ]] \
  || { printf 'Immutable release provenance is missing.\n' >&2; exit 1; }
python3 -B "$script_dir/agent_release.py" verify-provenance "$release_source_directory" "$asset_directory"
jq -e \
  --arg repository "$GITHUB_REPOSITORY" \
  --arg workflow "$GITHUB_WORKFLOW" \
  --arg workflow_ref "$expected_workflow_ref" \
  --arg run_id "$GITHUB_RUN_ID" \
  --arg run_attempt "$provenance_run_attempt" \
  --argjson release_id "$release_id" \
  --arg ref "$GITHUB_REF" \
  --arg ref_name "$tag" \
  --arg source "$source_sha" '
    .schemaVersion == 1
    and .buildType == "https://sunderapp.io/provenance/github-actions/v1"
    and .invocation.repository == $repository
    and .invocation.workflow == $workflow
    and .invocation.workflowRef == $workflow_ref
    and .invocation.runId == $run_id
    and .invocation.runAttempt == $run_attempt
    and .invocation.releaseId == $release_id
    and .invocation.ref == $ref
    and .invocation.refName == $ref_name
    and .invocation.sha == $source
  ' "$release_provenance" >/dev/null \
  || { printf 'Immutable release provenance does not match the same run, tag, source, release, and origin attempt.\n' >&2; exit 1; }

release_json="$(gh api "repos/$GITHUB_REPOSITORY/releases/$release_id")"
jq -e --argjson id "$release_id" --arg tag "$tag" '
  .id == $id and .tag_name == $tag and .draft == true
  and ([.assets[].id] | length) == ([.assets[].id] | unique | length)
' <<< "$release_json" >/dev/null \
  || { printf 'Numeric release identity changed before publication handoff.\n' >&2; exit 1; }
assets='[]'
for asset in "${release_assets[@]}"; do
  name="$(basename "$asset")"
  [[ "$name" =~ ^[A-Za-z0-9][A-Za-z0-9._+-]*$ ]] \
    || { printf 'Immutable release asset has an unsafe flat name: %s\n' "$name" >&2; exit 1; }
  asset_id="$(jq -er --arg name "$name" --arg digest "sha256:$(hash_file "$asset")" \
    --argjson size "$(wc -c < "$asset" | tr -d '[:space:]')" '
      [.assets[] | select(.name == $name and .digest == $digest and .size == $size and .state == "uploaded")]
      | if length == 1 then .[0].id | select(type == "number" and floor == . and . > 0) else error("asset identity") end
    ' <<< "$release_json")" || { printf 'Numeric asset identity differs for %s.\n' "$name" >&2; exit 1; }
  assets="$(jq -cn \
    --argjson assets "$assets" \
    --argjson id "$asset_id" \
    --arg path "$name" \
    --arg sha256 "$(hash_file "$asset")" \
    --argjson size "$(wc -c < "$asset" | tr -d '[:space:]')" \
    '$assets + [{id:$id,path:$path,sha256:$sha256,size:$size}]')"
done
release_assets_sha256="$(jq -cS '[.[] | {path,sha256,size}] | sort_by(.path)' <<< "$assets" | hash_stream)"
[[ "$release_assets_sha256" == "$verified_release_assets_sha256" ]] \
  || { printf 'Downloaded release assets differ from the publisher verified byte inventory.\n' >&2; exit 1; }

next="$handoff.next"
trap 'rm -f "$next"' EXIT
jq -nS \
  --arg repository "$GITHUB_REPOSITORY" \
  --arg workflow "$GITHUB_WORKFLOW" \
  --arg workflow_ref "$expected_workflow_ref" \
  --arg run_id "$GITHUB_RUN_ID" \
  --arg run_attempt "$GITHUB_RUN_ATTEMPT" \
  --argjson release_id "$release_id" \
  --arg ref "$GITHUB_REF" \
  --arg ref_name "$tag" \
  --arg source "$source_sha" \
  --arg provenance_run_attempt "$provenance_run_attempt" \
  --arg provenance_sha256 "$(hash_file "$release_provenance")" \
  --arg lock_set_sha256 "$(jq -r '.lockSetSha256' "$release_provenance")" \
  --arg release_assets_sha256 "$release_assets_sha256" \
  --argjson assets "$assets" '
    {
      schemaVersion: 1,
      buildType: "https://sunderapp.io/provenance/github-actions-publication-handoff/v1",
      invocation: {
        repository: $repository,
        workflow: $workflow,
        workflowRef: $workflow_ref,
        runId: $run_id,
        runAttempt: $run_attempt,
        releaseId: $release_id,
        ref: $ref,
        refName: $ref_name,
        sha: $source
      },
      immutableRelease: {
        artifactSourceCommit: $source,
        lockSetSha256: $lock_set_sha256,
        provenanceRunAttempt: $provenance_run_attempt,
        provenanceSha256: $provenance_sha256,
        assetsSha256: $release_assets_sha256,
        assets: $assets
      }
    }
  ' > "$next"
mv "$next" "$handoff"
trap - EXIT
printf 'Generated current-attempt publication handoff for run %s attempt %s over immutable release provenance attempt %s.\n' \
  "$GITHUB_RUN_ID" "$GITHUB_RUN_ATTEMPT" "$provenance_run_attempt"
